-- Blur for the Mirador overview only. Omarchy ships with blur off; turning
-- the engine on would also blur behind every window (they're 96-98.5% opaque),
-- so windows opt back out and only the layer rule below gets blur.
hl.config({
  decoration = {
    blur = {
      enabled = true,
    },
  },
})

o.window(".*", { no_blur = true })

hl.layer_rule({
  name = "mirador-blur",
  match = { namespace = "^omarchy-workspace-overview$" },
  blur = true,
})
